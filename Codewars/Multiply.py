def multiply(a, b):
    """Multiplica dos números y devuelve el resultado de la operación.

    PARAMETERS
    ---
    a (int): El primer número (factor) a multiplicar.
    b (int): El segundo número (factor) a multiplicar.

    RETURNS
    ---
    int: Devuelve el resultado de la multiplicación de `a` y `b`.
    """
    return a * b  # devuelve el resultado de la multiplicacion de a y b


print(multiply(2, 3))
